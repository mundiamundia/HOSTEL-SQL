CREATE OR REPLACE FUNCTION trg_allocation_guard_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_capacity integer; v_occupied integer;
BEGIN
 IF NEW.status='ACTIVE' THEN
  SELECT capacity INTO v_capacity FROM rooms WHERE room_id=NEW.room_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room'; END IF;
  IF EXISTS(SELECT 1 FROM allocations a WHERE a.student_id=NEW.student_id AND a.status='ACTIVE'
      AND (TG_OP='INSERT' OR a.allocation_id<>NEW.allocation_id)) THEN
    RAISE EXCEPTION 'Student already has an ACTIVE allocation';
  END IF;
  SELECT COUNT(*) INTO v_occupied FROM allocations a
   WHERE a.room_id=NEW.room_id AND a.status='ACTIVE'
     AND (TG_OP='INSERT' OR a.allocation_id<>NEW.allocation_id);
  IF v_occupied>=v_capacity THEN RAISE EXCEPTION 'Room has no free beds'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_allocation_guard BEFORE INSERT OR UPDATE ON allocations
FOR EACH ROW EXECUTE FUNCTION trg_allocation_guard_fn();

